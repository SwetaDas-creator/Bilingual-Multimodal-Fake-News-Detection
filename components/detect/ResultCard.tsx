import { CircleHelp, Info, ShieldAlert, ShieldCheck } from "lucide-react";
import type {
  DetectionMode,
  DetectionResponse,
  Verdict,
} from "@/types/detection";

/** Presentation config for each verdict. Colours convey meaning, but text and icon are always shown too (not colour-only). */
const VERDICT_STYLES: Record<
  Verdict,
  {
    label: string;
    icon: React.ElementType;
    badge: string;
    bar: string;
    border: string;
  }
> = {
  likely_fake: {
    label: "Likely Fake",
    icon: ShieldAlert,
    badge: "bg-red-100 text-red-800 border-red-300",
    bar: "bg-red-500",
    border: "border-t-red-500",
  },
  likely_real: {
    label: "Likely Real",
    icon: ShieldCheck,
    badge: "bg-green-100 text-green-800 border-green-300",
    bar: "bg-green-500",
    border: "border-t-green-500",
  },
  uncertain: {
    label: "Uncertain",
    icon: CircleHelp,
    badge: "bg-yellow-100 text-yellow-800 border-yellow-300",
    bar: "bg-yellow-500",
    border: "border-t-yellow-500",
  },
};

const MODE_LABELS: Record<DetectionMode, string> = {
  "bangla-text": "Bengali Text",
  "english-text": "English Text",
  "image-only": "Image Only",
  multimodal: "Text + Image (Multimodal)",
};

interface Props {
  result: DetectionResponse;
}

/** Formats a 0..1 score as a percentage; clamps to a valid range. */
function formatConfidence(value: number): string {
  const pct = Math.min(Math.max(value, 0), 1) * 100;
  return `${pct.toFixed(1)}%`;
}

export default function ResultCard({ result }: Props) {
  const style = VERDICT_STYLES[result.verdict];
  const Icon = style.icon;
  const pct = Math.min(Math.max(result.confidence, 0), 1) * 100;

  return (
    <section
      aria-labelledby="result-heading"
      className={`overflow-hidden rounded-xl border border-slate-200 border-t-4 bg-white shadow-sm ${style.border}`}
    >
      <div className="space-y-6 p-5 sm:p-8">
        {/* Header: verdict */}
        <div className="flex flex-wrap items-center justify-between gap-3">
          <h2
            id="result-heading"
            className="text-lg font-semibold text-slate-900"
          >
            Prediction Result
          </h2>
          <span
            className={`inline-flex items-center gap-2 rounded-full border px-4 py-1.5 text-sm font-semibold ${style.badge}`}
          >
            <Icon className="h-4 w-4" aria-hidden="true" />
            {style.label}
          </span>
        </div>

        {/* Confidence */}
        <div>
          <div className="mb-1 flex items-baseline justify-between">
            <span className="text-sm font-medium text-slate-600">
              Confidence score
            </span>
            <span className="text-2xl font-semibold text-slate-900">
              {formatConfidence(result.confidence)}
            </span>
          </div>
          <div
            className="h-2.5 w-full overflow-hidden rounded-full bg-slate-200"
            role="progressbar"
            aria-valuenow={Math.round(pct)}
            aria-valuemin={0}
            aria-valuemax={100}
            aria-label="Model confidence"
          >
            <div
              className={`h-full rounded-full ${style.bar}`}
              style={{ width: `${pct}%` }}
            />
          </div>
        </div>

        {/* Metadata grid */}
        <dl className="grid grid-cols-1 gap-4 rounded-lg bg-slate-50 p-4 sm:grid-cols-3">
          <div>
            <dt className="text-xs font-medium uppercase tracking-wide text-slate-500">
              Detection mode
            </dt>
            <dd className="mt-1 text-sm font-medium text-slate-900">
              {MODE_LABELS[result.mode]}
            </dd>
          </div>
          <div>
            <dt className="text-xs font-medium uppercase tracking-wide text-slate-500">
              Language
            </dt>
            <dd className="mt-1 text-sm font-medium text-slate-900">
              {result.language}
            </dd>
          </div>
          <div>
            <dt className="text-xs font-medium uppercase tracking-wide text-slate-500">
              Model used
            </dt>
            <dd className="mt-1 text-sm font-medium text-slate-900">
              {result.model}
            </dd>
          </div>
        </dl>

        {/* Explanation */}
        <div>
          <h3 className="text-sm font-semibold text-slate-800">Explanation</h3>
          <p className="mt-1 text-sm leading-relaxed text-slate-700">
            {result.explanation}
          </p>
        </div>

        {/* Mock-data notice: only shown when the API flags the response as mock */}
        {result.isMock && (
          <p className="rounded-md border border-slate-200 bg-slate-50 px-3 py-2 text-xs text-slate-500">
            Demo mode: this result was generated by the mock API and does not
            reflect real model output.
          </p>
        )}

        {/* Disclaimer */}
        <div className="flex items-start gap-2 rounded-md border border-blue-200 bg-blue-50 p-3 text-sm text-blue-900">
          <Info className="mt-0.5 h-4 w-4 flex-none" aria-hidden="true" />
          <p>
            This output is an AI-generated assessment, not definitive fact
            verification.
          </p>
        </div>
      </div>
    </section>
  );
}
