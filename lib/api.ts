import type {
  DetectionRequest,
  DetectionResponse,
  Verdict,
} from "@/types/detection";

// Set NEXT_PUBLIC_API_URL in .env.local to hit the real FastAPI backend.
// If it's unset/empty, the mock below is used so the UI can be developed standalone.
const API_URL = process.env.NEXT_PUBLIC_API_URL;

/** Human-readable model name per mode (replace with whatever the backend reports). */
const MODEL_BY_MODE: Record<DetectionRequest["mode"], string> = {
  "bangla-text": "BanglaBERT",
  "english-text": "BERT",
  "image-only": "ResNet / ViT image classifier",
  multimodal: "Multimodal fusion (text encoder + image encoder)",
};

const wait = (ms: number, signal?: AbortSignal) =>
  new Promise<void>((resolve, reject) => {
    const t = setTimeout(resolve, ms);
    signal?.addEventListener("abort", () => {
      clearTimeout(t);
      reject(new DOMException("Aborted", "AbortError"));
    });
  });

/** Mock: simulates latency and returns a randomised placeholder prediction. */
async function mockDetect(
  req: DetectionRequest,
  signal?: AbortSignal
): Promise<DetectionResponse> {
  await wait(1500 + Math.random() * 1000, signal);

  const verdicts: Verdict[] = ["likely_fake", "likely_real", "uncertain"];
  const verdict = verdicts[Math.floor(Math.random() * verdicts.length)];
  // Placeholder confidence only; real values come from the model
  const confidence =
    verdict === "uncertain"
      ? 0.45 + Math.random() * 0.15
      : 0.7 + Math.random() * 0.28;

  return {
    verdict,
    confidence,
    mode: req.mode,
    language: req.language,
    model: MODEL_BY_MODE[req.mode],
    explanation:
      "This is a mock response generated by the frontend for UI development. " +
      "In the final system, this section will summarise the signals the model relied on.",
    isMock: true,
  };
}

async function responseErrorMessage(res: Response): Promise<string> {
  const fallback =
    res.status >= 500
      ? "The detection server encountered an error. Please try again later."
      : "The request was rejected by the server. Please check your input.";
  try {
    const payload: unknown = await res.json();
    if (typeof payload === "object" && payload !== null && "detail" in payload) {
      const detail = (payload as { detail?: unknown }).detail;
      if (typeof detail === "string") return detail;
      if (Array.isArray(detail)) {
        const messages = detail.flatMap((item: unknown) => {
          if (
            typeof item === "object" &&
            item !== null &&
            "msg" in item &&
            typeof (item as { msg?: unknown }).msg === "string"
          ) return [(item as { msg: string }).msg];
          return [];
        });
        if (messages.length) return messages.join(" ");
      }
    }
  } catch {
    // Keep the status-based fallback for non-JSON responses.
  }
  return fallback;
}

/** Real call: multipart/form-data POST to FastAPI. */
async function realDetect(
  req: DetectionRequest,
  signal?: AbortSignal
): Promise<DetectionResponse> {
  const body = new FormData();
  body.append("mode", req.mode);
  body.append("language", req.language);
  if (req.text) body.append("text", req.text.trim());
  if (req.image) body.append("image", req.image);

  const res = await fetch(`${API_URL}/api/predict`, {
    method: "POST",
    body,
    signal,
  });

  if (!res.ok) {
    throw new Error(await responseErrorMessage(res));
  }
  return (await res.json()) as DetectionResponse;
}

/** Single entry point used by the UI. */
export async function detectNews(
  req: DetectionRequest,
  signal?: AbortSignal
): Promise<DetectionResponse> {
  try {
    return API_URL
      ? await realDetect(req, signal)
      : await mockDetect(req, signal);
  } catch (err) {
    if (err instanceof DOMException && err.name === "AbortError") throw err;
    if (err instanceof TypeError)
      throw new Error(
        "Could not reach the detection service. Check your connection and try again."
      );
    throw err;
  }
}
